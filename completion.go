package main

import (
	"fmt"
	"os/exec"
	"strings"
)

// noFileCompDirective is Cobra's ShellCompDirectiveNoFileComp: don't fall
// back to filename completion when there are no candidates.
const noFileCompDirective = ":4"

// runCompletionScript prints a shell completion script for wtcompose by
// taking docker's own generated completion script (which already knows how
// to complete every `docker compose` subcommand, flag, and service name)
// and renaming its identifiers/registration target from "docker" to
// "wtcompose". The only wtcompose-specific behavior is implemented once, in
// runComplete, which the renamed script calls into via `wtcompose
// __complete ...` exactly the way the original calls `docker __complete
// ...` — Cobra's generated scripts invoke the program name from the command
// line ($words[0]) rather than a hardcoded path, so renaming is sufficient.
func runCompletionScript(args []string) error {
	if len(args) != 1 {
		return fmt.Errorf("使い方: wtcompose completion <bash|zsh|fish>")
	}
	shell := args[0]
	switch shell {
	case "bash", "zsh", "fish":
	default:
		return fmt.Errorf("対応していないシェルです: %s(bash/zsh/fish のいずれか)", shell)
	}

	out, err := exec.Command("docker", "completion", shell).Output()
	if err != nil {
		return fmt.Errorf("docker completion %s の取得に失敗しました(docker がインストールされている必要があります): %w", shell, err)
	}

	fmt.Print(strings.ReplaceAll(string(out), "docker", "wtcompose"))
	return nil
}

// runComplete implements Cobra's hidden `__complete` protocol so the
// adapted scripts generated by runCompletionScript can request live
// completions from this binary. args are the words after "wtcompose" on
// the command line, truncated to the cursor position, with the final
// element always being the (possibly empty) word currently being typed.
//
// wtcompose has exactly one subcommand of its own ("herdr"); every other
// word maps 1:1 onto `docker compose <args>`, so completion is delegated
// there wholesale except for the two places herdr needs its own answer:
// offering "herdr" as a completion candidate for the very first word, and
// completing herdr's own flags once it's been chosen.
func runComplete(args []string) error {
	toComplete := ""
	if len(args) > 0 {
		toComplete = args[len(args)-1]
	}

	if len(args) >= 2 && args[0] == "herdr" {
		var candidates []string
		if strings.HasPrefix("--interval", toComplete) {
			candidates = append(candidates, "--interval\tpolling interval (default 5s)")
		}
		printCompletions(candidates, noFileCompDirective)
		return nil
	}

	out, _ := exec.Command("docker", append([]string{"__complete", "compose"}, args...)...).Output()
	lines := strings.Split(strings.TrimRight(string(out), "\n"), "\n")
	directive := noFileCompDirective
	var candidates []string
	if len(lines) > 0 {
		directive = lines[len(lines)-1]
		candidates = lines[:len(lines)-1]
	}

	if len(args) <= 1 && strings.HasPrefix("herdr", toComplete) {
		candidates = append(candidates, "herdr\tShow running container ports in herdr's sidebar")
	}

	printCompletions(candidates, directive)
	return nil
}

func printCompletions(candidates []string, directive string) {
	for _, c := range candidates {
		fmt.Println(c)
	}
	fmt.Println(directive)
}
