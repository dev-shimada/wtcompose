package override_test

import (
	"testing"

	"github.com/dev-shimada/wtcompose/internal/override"
)

func TestBuild_Golden(t *testing.T) {
	services := []override.Service{
		{
			Name:          "db",
			ContainerName: "myapp-feature-db",
			HasPorts:      true,
			Ports:         []override.PortLine{{Content: "20000:5432"}},
		},
		{
			Name:     "web",
			HasPorts: true,
			Ports: []override.PortLine{
				{Content: "20001:80"},
				{Content: "20002:5000/udp"},
			},
		},
		{
			Name: "worker",
		},
	}

	want := `# generated by compose-worktree-override
services:
  db:
    container_name: myapp-feature-db
    ports: !override
      - "20000:5432"
  web:
    ports: !override
      - "20001:80"
      - "20002:5000/udp"
`

	got := override.Build("", services)
	if got != want {
		t.Errorf("Build() mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

func TestBuild_LongSyntaxPort(t *testing.T) {
	services := []override.Service{
		{
			Name:     "web",
			HasPorts: true,
			Ports: []override.PortLine{
				{Content: "20000:80"},
				{Content: "target: 90\npublished: 20001\nprotocol: tcp\n", Long: true},
			},
		},
	}

	want := `# generated by compose-worktree-override
services:
  web:
    ports: !override
      - "20000:80"
      - target: 90
        published: 20001
        protocol: tcp
`

	got := override.Build("", services)
	if got != want {
		t.Errorf("Build() mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

func TestBuild_NothingToOverride(t *testing.T) {
	services := []override.Service{
		{Name: "worker"},
		{Name: "cache"},
	}

	if got := override.Build("", services); got != "" {
		t.Errorf("Build() = %q, want empty string when no service has container_name/ports", got)
	}
}

func TestBuild_ProjectName(t *testing.T) {
	services := []override.Service{
		{Name: "db", ContainerName: "myapp-feature-db"},
		{Name: "worker"},
	}

	want := `# generated by compose-worktree-override
name: "myapp-feature"
services:
  db:
    container_name: myapp-feature-db
`

	got := override.Build("myapp-feature", services)
	if got != want {
		t.Errorf("Build() mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

