func TestProjectName(t *testing.T) {
	tests := []struct {
		raw  string
		want string
	}{
		{"repo-a-feature-x", "repo-a-feature-x"},
		{"MyApp-Feature_X", "myapp-feature_x"},
		{"my.app-v1.2", "myapp-v12"},
		{"_private-wt", "private-wt"},
		{"-_-x", "x"},
		{"リポジトリ-feature", "feature"},
		{"日本語", ""},
		{"", ""},
	}
	for _, tt := range tests {
		if got := override.ProjectName(tt.raw); got != tt.want {
			t.Errorf("ProjectName(%q) = %q, want %q", tt.raw, got, tt.want)
		}
	}
}
